const dir = process.argv[2];
if (!dir) throw new Error('Pass the path to the Material Symbols "outlined" directory');

const lines = Object.entries(ICONS).map(([key, file]) => {
  const svg = readFileSync(path.join(dir, `${file}.svg`), 'utf8');
  const d = /<path d="([^"]+)"/.exec(svg)?.[1];
  if (!d) throw new Error(`No path in ${file}`);
  return `  ${key}: '${d}',`;
});

const out = `/**
 * GENERATED by scripts/extract-icons.mjs — do not edit by hand.
 * Path data from Material Symbols (Outlined, weight 400), © Google, Apache License 2.0:
 * https://github.com/google/material-design-icons — viewBox "0 -960 960 960".
 */
export const ICON_PATHS = {
${lines.join('\n')}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`;
mkdirSync(path.resolve('src/components/ui/icons'), { recursive: true });
writeFileSync(path.resolve('src/components/ui/icons/iconPaths.ts'), out);
console.info(`Wrote ${lines.length} icons`);

